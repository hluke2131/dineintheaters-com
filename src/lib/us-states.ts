export type USStateCode = (typeof US_STATES)[number]["code"];
export type USStateInfo = { code: USStateCode; name: string };

const SLUG_TO_STATE = new Map<string, USStateInfo>(
  US_STATES.map((state) => [state.code.toLowerCase(), state])
);

// Looks up a URL slug against the fixed list of US states, so an unrecognized
// slug can 404 instead of rendering a page for a state that will never exist.
// Distinct from "a real state with 0 listings yet", which should render
// normally with an empty state.
//
// The `locations.state` column (and every link built from it, e.g.
// slugify(location.state)) is always a 2-letter USPS code, never a full
// name — so the slug here is that code lowercased (e.g. "tx"), and the
// lookup is keyed the same way. Returns both the code (for querying the DB,
// which stores codes) and the full name (for display copy).
export function getStateBySlug(slug: string): USStateInfo | undefined {
  return SLUG_TO_STATE.get(slug.toLowerCase());
}
